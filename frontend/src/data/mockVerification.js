export function computeSummary(metrics) {
  if (!metrics || metrics.length === 0) return null
  const n = metrics.length
  const avg = (field) => (metrics.reduce((s, m) => s + m[field], 0) / n)
  const avgRmseRaw  = avg('rmse_raw')
  const avgRmseCorr = avg('rmse_corrected')
  const avgEtsRaw   = avg('ets_raw')
  const avgEtsCorr  = avg('ets_corrected')
  const best  = metrics.reduce((a, b) => b.ets_corrected > a.ets_corrected ? b : a)
  const worst = metrics.reduce((a, b) => b.ets_corrected < a.ets_corrected ? b : a)
  return {
    total_events: metrics.reduce((s, m) => s + m.event_count, 0),
    avg_rmse_raw: parseFloat(avgRmseRaw.toFixed(2)),
    avg_rmse_corrected: parseFloat(avgRmseCorr.toFixed(2)),
    avg_ets_raw: parseFloat(avgEtsRaw.toFixed(3)),
    avg_ets_corrected: parseFloat(avgEtsCorr.toFixed(3)),
    rmse_improvement_pct: parseFloat(((avgRmseRaw - avgRmseCorr) / avgRmseRaw * 100).toFixed(1)),
    ets_improvement_pct: parseFloat(((avgEtsCorr - avgEtsRaw) / avgEtsRaw * 100).toFixed(1)),
    best_regime: best.regime,
    worst_regime: worst.regime,
  }
}
